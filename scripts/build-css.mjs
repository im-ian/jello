// Generates dist/jello.css: a zero-JS version of the press effect.
// The spring curves are baked into CSS linear() easings by the same code the
// JS uses, so both versions feel the same (minus velocity on interruption).
import { writeFileSync } from 'node:fs'
import { presets, springEasing } from '../dist/index.js'

const r = (n) => Number(n.toFixed(4))

function vars(p) {
  const press = springEasing(p.press)
  const release = springEasing(p.release)
  const s = 1 - p.depth
  const q = 1 - p.squash
  return [
    `  --jello-sx: ${r(s / q)};`,
    `  --jello-sy: ${r(s * q)};`,
    `  --jello-press-duration: ${press.duration}ms;`,
    `  --jello-press-easing: ${press.easing};`,
    `  --jello-release-duration: ${release.duration}ms;`,
    `  --jello-release-easing: ${release.easing};`,
  ].join('\n')
}

const css = `/* jello.css — generated by scripts/build-css.mjs. Do not edit by hand.
 *
 * 1) Helpers for anything jello's JS handles ([data-jello]).
 * 2) .jello — a CSS-only press effect using spring easings baked into linear().
 *    Needs no JavaScript, but a CSS transition can't keep momentum when it is
 *    interrupted (fast repeated taps), which the JS version does.
 */

[data-jello] {
  -webkit-tap-highlight-color: transparent; /* the grey flash on mobile fights the squish */
  touch-action: manipulation; /* no double-tap-to-zoom delay on buttons */
}

.jello {
${vars(presets.wobbly)}
  transition: scale var(--jello-release-duration) var(--jello-release-easing);
}
.jello:active {
  scale: var(--jello-sx) var(--jello-sy);
  transition-duration: var(--jello-press-duration);
  transition-timing-function: var(--jello-press-easing);
}
${['gentle', 'bouncy', 'firm'].map((name) => `.jello--${name} {\n${vars(presets[name])}\n}`).join('\n')}

@media (prefers-reduced-motion: reduce) {
  .jello {
    transition: opacity 160ms ease-out;
  }
  .jello:active {
    scale: none;
    opacity: 0.7;
  }
}
`

writeFileSync(new URL('../dist/jello.css', import.meta.url), css)
console.log(`dist/jello.css  ${(Buffer.byteLength(css) / 1024).toFixed(1)} kB`)
